def validate(root: Path, data: dict[str, object]) -> list[str]:
    errors: list[str] = []
    if data.get("version") != 1:
        errors.append("matrix version must be 1")
    rows = data.get("case")
    if not isinstance(rows, list) or len(rows) != 7:
        return errors + ["case must contain the seven coherent RFC-3 positions"]
    required = {"id", *FIELDS, "engineer_label"}
    for row in rows:
        if not isinstance(row, dict) or set(row) != required:
            errors.append("every row must contain exactly the authoritative fields plus engineer_label")
    if errors:
        return errors
    ids = [row["id"] for row in rows]
    if len(ids) != len(set(ids)):
        errors.append("case ids must be unique")
    if ids != list(CANONICAL_FORMAL):
        errors.append("case ids/order must equal the seven canonical certification families")
    for row in rows:
        expected = CANONICAL_FORMAL.get(row["id"])
        actual = [row[field] for field in FIELDS]
        if expected is not None and actual != expected:
            errors.append(f"{row['id']}: authoritative mapping differs from the canonical family")
    exact = {
        "scope": {"none", "per_execution", "bounded:8", "all"},
        "refutation": {"none", "abort", "trace:8", "incomplete", "complete", "empirical"},
        "residual_trust": {"fiat", "solver", "lean_checked"},
        "boundary_kind": {"end_to_end", "to_boundary", "to_platform"},
        "classification_verdict": {"admitted", "rejected", "unknown"},
        "policy_point": {"runtime", "bounded", "solver_complete", "lean_empirical"},
    }
    for field, expected in exact.items():
        actual = {row[field] for row in rows}
        if actual != expected:
            errors.append(f"{field} coverage mismatch: {sorted(actual)}")
    for source, needles in {
        "forge/src/manifest.rs": ["CertificationPosition", "ClassificationCertificate"],
        "forge/src/rfc3_replay.rs": ["FormalReplay", "engineer_label_is_structurally_non_authoritative"],
    }.items():
        text = (root / source).read_text(encoding="utf-8")
        for needle in needles:
            if needle not in text:
                errors.append(f"{source}: missing {needle}")
    return errors


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    root = args.root.resolve()
    try:
        data = json.loads((root / MATRIX).read_text(encoding="utf-8"))
        errors = validate(root, data)
        output = generated(data["case"]) if not errors else ""
        target = root / LEAN
        if args.write and not errors:
            target.write_text(output, encoding="utf-8")
        elif not errors and (not target.exists() or target.read_text(encoding="utf-8") != output):
            errors.append(f"{LEAN} is stale; run gates/rfc3-certification-replay.py --write")
    except (OSError, json.JSONDecodeError, KeyError, TypeError) as error:
        print(f"RFC-3 certification replay: INCONCLUSIVE: {error}", file=sys.stderr)
        return 3
    if errors:
        print("RFC-3 certification replay: FAIL", file=sys.stderr)
        for error in errors:
            print(f"  - {error}", file=sys.stderr)
        return 1
    print("RFC-3 certification replay: clean: 7 positions, 14 authoritative mutation pins")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
