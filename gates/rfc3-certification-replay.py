def lean_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def lean_list(values: list[str]) -> str:
    return "[" + ", ".join(lean_string(value) for value in values) + "]"


def row_expr(row: dict[str, object]) -> str:
    parts = []
    for field in ["id", *FIELDS, "engineer_label"]:
        value = row[field]
        rendered = str(value) if isinstance(value, int) else lean_list(value) if isinstance(value, list) else lean_string(value)
        parts.append(f"    {field} := {rendered}")
    return "  {\n" + "\n".join(parts) + " }"


